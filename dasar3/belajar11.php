<?php
 
$x = 80;
$y = 29;
 
// bitwise AND
$z = $x & $y;
echo "$x & $y = $z";
echo "<br>";
 
// bitwise OR
$z = $x | $y;
echo "$x | $y = $z";
echo "<br>";
 
// bitwise XOR
$z = $x ^ $y;
echo "$x ^ $y = $z";
echo "<br>";
 
// Shift Left
$z = $x << $y;
echo "$x << $y = $z";
echo "<br>";
 
// Shift Right
$z = $x >> $y;
echo "$x >> $y = $z";
echo "<br>";
 
?>